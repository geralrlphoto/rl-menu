/** Limpa horário "DD/MM/YYYY — HH:MM" → "DD/MM/YYYY" */
function stripTimeT(d: string): string { return (d || '').split('—')[0].trim() }

/** Converte user-project (formato de /novos-projetos) para Project tipo do _data */
function userProjectToProjectT(p: any): Project {
  const pacote = p.pacote ?? 'Pacote Premium 👑'
  return {
    id: p.id,
    noivos: p.noivos ?? '—',
    foto: p.foto || 'https://images.unsplash.com/photo-1519741497674-611481863552?w=900&h=600&fit=crop',
    email: '', telefone: '',
    recebido: stripTimeT(p.recebido || ''),
    dataCasamento: p.dataCasamento || '',
    entregaPrevista: p.entregaPrevista || '',
    pacote, preco: pacote === 'Pacote Essencial' ? 1800 : 3500,
    duracao: p.duracao || '',
    stage: p.stage ?? 'Novo Projeto',
    approval: p.approval ?? 'Aguardando Revisão',
    progress: 0,
    editor: p.editor || 'Editor Pro',
    finalEntregue: p.stage === 'Entregue',
    finalLink: p.finalLink || '',
  }
}

/** Gera tarefas automáticas para um projeto criado pelo utilizador */
function generateTasksForUserProject(p: any): Task[] {
  const auto: { title: string; priority: Priority; daysAfterCreate: number }[] = [
    { title: 'Importar material',     priority: 'Alta',  daysAfterCreate: 0 },
    { title: 'Organizar ficheiros',   priority: 'Média', daysAfterCreate: 1 },
    { title: 'Iniciar edição',        priority: 'Alta',  daysAfterCreate: 3 },
    { title: 'Color grading',         priority: 'Média', daysAfterCreate: 7 },
    { title: 'Enviar primeira versão', priority: 'Alta', daysAfterCreate: 14 },
  ]
  const recebido = stripTimeT(p.recebido || TODAY)
  const [d, m, y] = recebido.split('/').map(Number)
  return auto.map((t, i) => {
    const dt = new Date(y, m-1, d); dt.setDate(dt.getDate() + t.daysAfterCreate)
    const deadline = `${String(dt.getDate()).padStart(2,'0')}/${String(dt.getMonth()+1).padStart(2,'0')}/${dt.getFullYear()}`
    return {
      id: `${p.id}-task-${i}`,
      title: t.title,
      projectId: p.id,
      assignee: 'Editor Pro',
      assigneeAvatar: AVATAR_EDITOR,
      deadline,
      priority: t.priority,
      status: 'Pendente' as TaskStatus,
      progress: 0,
      autoGenerated: true,
    }
  })
}

